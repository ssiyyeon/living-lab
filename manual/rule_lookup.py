def load_situations() -> dict:
    with open(SITUATIONS_PATH, encoding="utf-8") as f:
        situations = json.load(f)
    for s in situations:
        s["처리방법"] = _clean_lines(s.get("처리방법", []))
        s["참고사항"] = _clean_lines(s.get("참고사항", []))
    return {(s["부서"], s["민원요지"]): s for s in situations}


def match_manual(text: str) -> list[dict]:
    """민원내용 텍스트에서 매뉴얼 상황 키워드를 찾아 (부서, 민원요지, 매칭키워드) 목록 반환"""
    hits = []
    for (dept, situation), kws in KEYWORDS.items():
        for kw in kws:
            if kw in text:
                hits.append({"부서": dept, "민원요지": situation, "매칭키워드": kw})
                break
    return hits


