# PDF 파싱 과정에서 섞여 들어온 순수 잡음(페이지 번호, 흐름 화살표, 빈 구분선).
# 표가 깨져서 남은 "30", "구분" 같은 셀 조각은 원문 맥락을 잃을 위험이 있어 건드리지 않는다.
_NOISE_LINE_PATTERNS = [
    re.compile(r"^-\s*\d+\s*-$"),  # 페이지 마커: "- 52 -"
    re.compile(r"^▼+$"),           # 흐름 화살표만 있는 줄
    re.compile(r"^-$"),            # 단독 하이픈
]


def _is_noise_line(line: str) -> bool:
    s = line.strip()
    return any(p.match(s) for p in _NOISE_LINE_PATTERNS)


def _clean_lines(lines: list[str]) -> list[str]:
    return [l for l in lines if not _is_noise_line(l)]

